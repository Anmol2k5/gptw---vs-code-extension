const dicts: Record<Locale, Dict> = { en, es, fr, de, ja, "zh-CN": zh };

export function detectLocale(): Locale {
  try {
    const raw = JSON.parse(process.env.VSCODE_NLS_CONFIG ?? "{}")
      .locale as string | undefined;
    if (raw === "zh-cn") return "zh-CN";
    if ((raw ?? "").startsWith("zh")) return "zh-CN";
    if (raw === "ja") return "ja";
    if (raw === "de") return "de";
    if (raw === "fr") return "fr";
    if (raw === "es") return "es";
    return "en";
  } catch { return "en"; }
}

export function availableLocales(): { code: Locale; name: string }[] {
  return [
    { code: "en", name: "English" },
    { code: "es", name: "Español" },
    { code: "fr", name: "Français" },
    { code: "de", name: "Deutsch" },
    { code: "ja", name: "日本語" },
    { code: "zh-CN", name: "简体中文" },
  ];
}

export function t(key: string, vars?: Record<string, string>, locale?: Locale): string {
  const l = locale ?? detectLocale();
  const dict = dicts[l] ?? dicts.en;
  let msg = dict[key] ?? dicts.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      msg = msg.replace(new RegExp(`\\{${k}\\}|\\$\\{${k}\\}`, "g"), v);
    }
  }
  return msg;
}
